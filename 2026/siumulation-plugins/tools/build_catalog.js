// Rebuilds plugins.js from _manifest.json + the metadata each built plugin registers.
// Usage: node siumulation-plugins/tools/build_catalog.js   (run from the archive root or anywhere)
const fs = require('fs'), path = require('path'), vm = require('vm');
const dir = path.join(__dirname, '..');
const M = JSON.parse(fs.readFileSync(path.join(dir, '_manifest.json'), 'utf8'));
const out = [];
for (const m of M) {
  const f = path.join(dir, m.file);
  const e = { id: m.id, file: m.file, folder: m.folder, family: m.family, tier: m.tier, status: m.status, product: m.product || null };
  if (m.status === 'ready' && fs.existsSync(f)) {
    const reg = [];
    const noop = () => {};
    // permissive stand-in: any property is a callable that returns another stand-in
    const any = () => new Proxy(function(){}, { get: (t, k) => k === Symbol.toPrimitive ? (() => '') : k === 'length' ? 0 : k === Symbol.iterator ? function*(){} : k === 'then' ? undefined : any(), apply: () => any(), construct: () => any() });
    const el = () => any();
    const ctx = { console, Math, Date, JSON, Array, Object, String, Number, Promise, setTimeout: noop, setInterval: noop, clearInterval: noop, clearTimeout: noop, requestIdleCallback: noop, performance: { now: () => 0 },
      document: Object.assign(el(), { createElement: el, body: el(), documentElement: el() }), location: { search: '', hash: '' }, navigator: {}, localStorage: { getItem: () => null, setItem: noop },
      requestAnimationFrame: noop, getComputedStyle: () => ({ getPropertyValue: () => '' }), matchMedia: () => ({ matches: false }) };
    ctx.window = ctx; ctx.addEventListener = noop; ctx.removeEventListener = noop; ctx.innerWidth = 1400; ctx.devicePixelRatio = 1; ctx.Image = function(){ return any(); };
    ctx.SIM = ctx.window.SIM = { register: p => reg.push(p), on: noop, emit: noop, refresh: noop, seek: noop, css: () => '', year: y => y + '|' + (y - 1967), fmtT: String, fmtDur: String, el, canvas: noop, dotMatrix: () => '', drawLanes: noop, pulses: noop, window: () => [0, 1], niceStep: x => x, src: (p, l) => String(l || p) };
    try { vm.runInNewContext(fs.readFileSync(f, 'utf8'), ctx, { filename: m.file, timeout: 5000 }); } catch (err) { e.error = String(err).slice(0, 200); }
    const p = reg.find(r => r.id === m.id) || reg[0];
    if (p) {
      Object.assign(e, { status: 'ready', name: p.name, product: p.product || m.product || p.name, year: p.year || null, summary: p.summary || '', highlights: p.highlights || [], footnotes: (p.footnotes || []).map(n => typeof n === 'string' ? { text: n } : { text: n.text, src: n.src || undefined }), depth: p.depth || (m.tier === 'full' ? 'Full model' : 'Hardware model'), tabs: (p.tabs || []).map(t => ({ id: t.id, label: t.label })) });
      if (p.id !== m.id) e.idMismatch = p.id;
    } else if (!e.error) e.error = 'no SIM.register() call found';
  }
  out.push(e);
}
const ready = out.filter(e => e.status === 'ready').length;
fs.writeFileSync(path.join(dir, 'plugins.js'),
  '/* WBS Device Simulator — plugin catalogue. GENERATED by tools/build_catalog.js from _manifest.json; do not edit by hand.\n' +
  '   Each entry is one product. status "ready" = its plugin file exists and registered; others are still to be built. */\n' +
  'window.SIM_CATALOG = ' + JSON.stringify(out, null, 1) + ';\n' +
  'window.SIM_PLUGIN_FILES = window.SIM_CATALOG.filter(e => e.status === "ready").map(e => e.file);\n');
console.log(`catalogue: ${out.length} products, ${ready} ready` + out.filter(e => e.error).map(e => `\n  ERROR ${e.id}: ${e.error}`).join(''));
