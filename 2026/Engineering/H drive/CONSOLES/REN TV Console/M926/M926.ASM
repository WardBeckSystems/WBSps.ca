;*******************  REFRESH ***********************************

;     REFRESH  - TRANSMITS CROSSPOINT TABLE TO 74HC4094'S


CLK	EQU 3	; PORTA BIT 3
STR	EQU 4	; PORTA BIT 4
DATAA	EQU 6	;PORTC BIT 6
;TEMP1  TEMP FILE REGISTER	
;TEMP2	BIT COUNT

REFRESH
	BANK1
	BCF TRISC,6	;DATA PIN IS OUTPUT
	BCF TRISA,4	;STROBE PIN IS OUTPUT
 	BCF TRISA,3	;CLOCK PIN IS OUTPUT
	BANK0
	BCF PORTA,CLK
;output shout table
	MOVF SHOUT0,W
	;BTFSS M926-0,X		;IS CHANNEL ON
	;AND W WITH XPT0 ;
	CALL CLKBYTE
	MOVF SHOUT1,W
	CALL CLKBYTE
	MOVF SHOUT2,W
	CALL CLKBYTE
	MOVF SHOUT3,W
	CALL CLKBYTE

	BCF PORTA,STR
	NOP
	BSF PORTA,STR
	BCF PORTA,STR
;	BANK1
;	BSF TRISA,2	;DATAA PIN IS INPUT
;	BANK0
	RETURN

; CLOCK BYTE IN W REGISTER TO 74HC4094'S

CLKBYTE	
	MOVWF TEMP1
	MOVLW 8
	MOVWF TEMP2	;BIT COUNT

NXTBIT	RRF TEMP1,F
	BTFSC STATUS,0
	GOTO ONE
	BCF PORTC,DATAA
	BSF PORTA,CLK
	BCF PORTA,CLK
	DECFSZ TEMP2,F
	GOTO NXTBIT
	RETURN

ONE 	BSF PORTC,DATAA
	BSF PORTA,CLK
	BCF PORTA,CLK
	DECFSZ TEMP2,F
	GOTO NXTBIT
	RETURN

		
;****************  DELAY ROUTINE *****************************


; INIT DELAY 2 BEFORE ENTERING
; DELAY=:: DELAY1(255*1/1.25MHZ*2 * DELAY2)

DELAY
	MOVLW 0XFF
DEL1	MOVWF DELAY1
DEC1	DECFSZ DELAY1,F
	GOTO DEC1
	DECFSZ DELAY2,F
	GOTO DEL1
	RETURN

