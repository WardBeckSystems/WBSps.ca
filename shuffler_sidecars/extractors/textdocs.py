def _headings_and_pars(text, report):
    """Split text into paragraphs; detect headings (setext underlines, boxed titles,
    ** TITLE **, Quartus '; Title ;' tables). Lines kept within blocks."""
    lines = [l.rstrip() for l in text.replace('\r\n', '\n').replace('\r', '\n').split('\n')]
    # repeated page-header line (e.g. MAX+plus 'Project Information  path')
    first = next((l.strip() for l in lines if l.strip()), '')
    repeat = first if first and sum(1 for l in lines if l.strip() == first) >= 3 else None
    out, buf = [], []
    seen_first = False

    def flush():
        while buf and not buf[-1].strip():
            buf.pop()
        while buf and not buf[0].strip():
            buf.pop(0)
        if buf:
            out.append(textwrap.dedent('\n'.join(buf)))
        buf.clear()

    i, n = 0, len(lines)
    while i < n:
        l = lines[i]
        s = l.strip()
        if repeat and s == repeat:
            if seen_first:
                i += 1; continue
            seen_first = True
        if not s:
            flush(); i += 1; continue
        if RULE.match(l):
            # boxed title: rule / text / rule
            if i + 2 < n and lines[i + 1].strip() and RULE.match(lines[i + 2]) and len(lines[i + 1].strip()) < 100 \
                    and (i + 3 >= n or not lines[i + 3].strip().startswith(';') or lines[i + 1].count(';') <= 2):
                flush()
                out.append({'heading': lines[i + 1].strip().strip(';|*= ').strip()})
                i += 3; continue
            flush(); i += 1; continue
        # setext underline
        if not buf and i + 1 < n and RULE.match(lines[i + 1]) and len(s) < 100 and re.search(r'[A-Za-z]', s) \
                and len(lines[i + 1].strip()) >= max(3, int(len(s) * 0.5)) and not (buf and buf[-1].strip() and report and '  ' in s.strip()):
            flush()
            out.append({'heading': s.strip('*=#- ')})
            i += 2; continue
        m = re.match(r'^\s*\*{2,}\s*([^*].*?)\s*\*{2,}\s*$', l)
        if m and len(m.group(1)) < 100:
            flush()
            out.append({'heading': m.group(1)})
            i += 1; continue
        m = re.match(r'^\s*(?:Section|SECTION)\s+(\d+[\w.]*)\s*[-:.]?\s*(.*)$', l)
        if m and len(s) < 100:
            flush()
            out.append({'heading': s})
            i += 1; continue
        buf.append(l)
        if len(buf) > 400:
            flush()
        i += 1
    flush()
    return out


def _count(text, pat):
    return len(re.findall(pat, text, re.M))


