def _md5(path, text):
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    ents = []
    for l in lines:
        m = re.match(r'^(?:MD5\s*\((.+)\)\s*=\s*([0-9a-fA-F]{32})|([0-9a-fA-F]{32})(?:\s+\*?(.*))?)$', l)
        if m:
            if m.group(2):
                ents.append((m.group(2).lower(), m.group(1)))
            else:
                ents.append((m.group(3).lower(), (m.group(4) or '').strip()))
    r = {'kind': 'data', 'type': 'MD5 checksum list'}
    name = os.path.basename(path)
    if len(ents) == 1 and not ents[0][1]:
        stem = name[:-4]
        what = 'call graph' if stem.endswith('_cgraph') else 'caller graph' if stem.endswith('_icgraph') else \
            'included-by dependency graph' if stem.endswith('__dep__incl') else 'include dependency graph' if stem.endswith('__incl') else \
            'class inheritance graph' if 'inherit' in stem else \
            'class/collaboration graph' if ('graph' in stem or 'coll' in stem) else 'graph'
        r['type'] = 'Doxygen graph checksum (MD5)'
        r['summary'] = (f'Doxygen {what} checksum: MD5 `{ents[0][0]}`. Doxygen stores this hash of the dot graph '
                        f'source so it can skip regenerating {stem}.png/.map when the graph is unchanged.')
        r['meta'] = [('MD5', f'`{ents[0][0]}`'), ('Graph image', stem + '.png')]
        r['keywords'] = ['Doxygen', 'graph', 'MD5']
        r['paragraphs'] = [ents[0][0]]
        return r
    if not ents:
        r['paragraphs'] = core.split_paragraphs(text)
        r['notes'] = ['No hash lines recognised.']
        return r
    r['summary'] = f'MD5 checksum list for {len(ents)} file{"s" if len(ents) != 1 else ""}' + \
        (': ' + ', '.join(os.path.basename(f) for _, f in ents[:10]) + (' …' if len(ents) > 10 else '') if any(f for _, f in ents) else '') + '.'
    r['outline'] = [f'`{h}` {f}' for h, f in ents[:5000]]
    r['meta'] = [('Entries', len(ents))]
    other = [l for l in lines if not re.match(r'^(MD5\s*\(|[0-9a-fA-F]{32})', l)]
    if other:
        r['paragraphs'] = ['\n'.join(other)]
    return r


