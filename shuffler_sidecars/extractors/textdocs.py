def extract(path):
    ext = _ext(path)
    try:
        if os.path.getsize(path) == 0:
            return {'kind': 'document', 'type': 'Empty file', 'summary': 'Empty file (0 bytes).'}
        if core.looks_binary(path):
            return _binary(path, ext)
        if ext in HTML_EXT:
            return _html(path)
        if ext in XML_EXT:
            return _xml(path, ext)
        text, trunc = core.read_text(path)
        if ext.endswith('preview') and text.lstrip().startswith('[Preview]'):
            return _preview(path, text)
        if ext == 'md5':
            return _md5(path, text)
        if ext in ('json', 'yaml', 'yml'):
            return _jsonyaml(path, ext, text)
        if ext in INI_EXT:
            # tool logs/reports with config-like extension (e.g. .cfg written by tools) still mostly key=value
            return _ini(path, ext, text)
        if ext in REPORT_EXT:
            return _report(path, ext, text, trunc)
        if ext in ('xml',):
            return _xml(path, ext)
        if text.lstrip()[:200].lower().startswith(('<!doctype html', '<html')):
            return _html(path)
        if text.lstrip().startswith('<?xml'):
            return _xml(path, ext)
        return _plaintext(path, ext, text, trunc)
    except Exception as e:  # never raise
        try:
            text, trunc = core.read_text(path)
            return {'kind': 'document', 'paragraphs': core.split_paragraphs(text),
                    'notes': [f'textdocs extractor fell back to plain split ({type(e).__name__}: {str(e)[:120]}).']}
        except Exception:
            return {'kind': 'binary', 'notes': [f'Unreadable ({type(e).__name__}).']}
