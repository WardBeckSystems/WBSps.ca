        if not funcs:
            imps = [i.get('file') for i in root.iter() if _local(i.tag) == 'import' and i.get('file')]
            summ = (f"Apache Ant build script{(' for project ' + repr(root.get('name'))) if root.get('name') else ''}"
                    + (f" importing {', '.join(imps)}" if imps else '') + '; defines no targets of its own.')
