def _ext(path):
    n = os.path.basename(path).lower()
    return n.rsplit('.', 1)[1] if '.' in n else ''


def _ws(s):
    return re.sub(r'[ \t\r\f\v\u00a0]+', ' ', s).strip()


# ======================================================================= binary
def _binary(path, ext):
    with open(path, 'rb') as f:
        data = f.read(4 << 20)
    strings = [m.group(0).decode('latin-1').strip() for m in re.finditer(rb'[\x20-\x7e]{6,}', data)]
    strings = [s for s in strings if len(set(s)) > 2][:300]
    if ext == 'cnf':
        strings = [m.group(0).decode('latin-1').strip() for m in re.finditer(rb'[\x21-\x7e][\x20-\x7e]{3,}', data)]
        strings = [s for s in strings if len(set(s)) > 2 and re.search(r'[A-Za-z]', s)][:300]
    typ = 'Binary file'
    if ext == 'cnf' and data[:3] == b'CNF':
        typ = 'Altera MAX+PLUS II compiler netlist (binary .cnf)'
        m = re.search(rb'[\x21-\x7e][\x20-\x7e]{2,}', data[4:200])
        nm = m.group(0).decode('latin-1').strip() if m and m.group(0) not in (b'AUTO',) else os.path.splitext(os.path.basename(path))[0]
        sig = list(dict.fromkeys(x for x in strings if re.match(r'^[A-Za-z_][\w\[\]~:.]*$', x)
                                 and x not in (nm, 'Untitled', 'AUTO')))[:12]
        summ = (f'Altera MAX+PLUS II compiler netlist file (CNF) for design "{nm}". Binary intermediate produced and '
                f'regenerated by the MAX+PLUS II compiler' + (f'; embedded node names include {", ".join(sig)}' if sig else '') + '.')
    else:
        summ = ''
    r = {'kind': 'binary', 'type': typ, 'meta': [('First bytes', '`' + data[:16].hex(' ') + '`')],
         'notes': ['Binary file: only embedded printable strings are listed.']}
    if summ:
        r['summary'] = summ
    if strings:
        r['outline'] = [{'heading': f'Embedded strings ({len(strings)})'}] + ['`' + s.replace('`', "'")[:160] + '`' for s in strings]
    return r


