HEAD = {'h1', 'h2', 'h3', 'h4', 'h5', 'h6'}


def _html_blocks(root, Tag, NavigableString, Comment):
    """Walk the tree; emit paragraphs (str) and headings ({'heading'})."""
    out = []
    buf = []
    state = {'cell': False}

    def flush():
        if buf:
            t = ''.join(buf)
            ls = []
            for x in t.split('\n'):
                x = _ws(x).strip()
                x = re.sub(r'^(\|\s*)+|(\s*\|)+$', '', x).strip()
                x = re.sub(r'(\|\s*){2,}', '| ', x)
                if x:
                    ls.append(x)
            t = '\n'.join(ls)
            if t and re.search(r'\w', t):
                out.append(t)
            buf.clear()

    tdepth = [0]
    stack = [(root, False)]
    while stack:
        node, closing = stack.pop()
        if closing:
            if node.name in HEAD:
                txt = _ws(''.join(buf).replace('\n', ' ')).strip(' |')
                buf.clear()
                if txt:
                    out.append({'heading': txt[:200]})
            elif node.name == 'table':
                tdepth[0] -= 1
                flush()
            elif node.name == 'tr' and tdepth[0] > 0:
                if buf and not ''.join(buf[-3:]).endswith('\n'):
                    buf.append('\n')
            elif node.name in BLOCK:
                if tdepth[0] > 0:
                    buf.append(' ')
                else:
                    flush()
            continue
        if isinstance(node, Comment):
            continue
        if isinstance(node, NavigableString):
            s = str(node)
            if s.strip():
                buf.append(s if node.parent is not None and node.parent.name == 'pre' else s.replace('\n', ' '))
            elif buf and not buf[-1].endswith(' '):
                buf.append(' ')
            continue
        if not isinstance(node, Tag):
            continue
        name = node.name
        if name in SKIP:
            continue
        if name == 'br':
            buf.append('\n')
            continue
        if name == 'tr':
            state['cells'] = 0
        if name in ('td', 'th'):
            if state.get('cells', 0) > 0:
                buf.append(' | ')
            else:
                buf.append(' ')
            state['cells'] = state.get('cells', 0) + 1
        if name == 'table':
            flush()
            tdepth[0] += 1
        elif name in HEAD or (name in BLOCK and tdepth[0] == 0):
            flush()
        elif name in BLOCK:
            buf.append(' ')
        if name == 'pre':
            for sub in node.find_all(['br', 'dt', 'dd', 'p', 'div', 'li', 'tr']):
                sub.insert_before('\n')
            t = node.get_text()
            t = '\n'.join(x.rstrip() for x in t.replace('\r', '').split('\n')).strip('\n')
            if t.strip():
                out.append(t)
            continue
        if name == 'img' and node.get('alt') and len(node['alt']) > 3:
            buf.append(f" [image: {node['alt']}] ")
            continue
        stack.append((node, True))
        for ch in reversed(list(node.children)):
            stack.append((ch, False))
    flush()
    return out


def _holds_content(t):
    """True when an element that looks like navigation actually wraps page content
    (unclosed nav <div> in old generated HTML)."""
    return t.find(['h1', 'h2', 'pre', 'dl']) is not None or t.find(class_=re.compile('^(contents|memitem|fragment)$')) is not None \
        or len(t.get_text()) > 4000


def _clean_heads(pars):
    """Drop headings directly followed by nothing; dedupe adjacent duplicates."""
    out = []
    for i, p in enumerate(pars):
        if out and p == out[-1]:
            continue
        out.append(p)
    while out and isinstance(out[-1], dict):
        out.pop()
    return out


def _doxygen_functions(soup, Tag):
    funcs = []
    kind = 'function'
    for el in soup.find_all(['h2', 'div']):
        if getattr(el, 'decomposed', False) or el.attrs is None:
            continue
        if el.name == 'h2':
            t = el.get_text(' ', strip=True).lower()
            for k, v in (('function', 'function'), ('define', 'macro'), ('variable', 'variable'),
                         ('typedef', 'typedef'), ('enum', 'enum'), ('field', 'field'), ('member', 'member'),
                         ('constructor', 'constructor')):
                if k in t:
                    kind = v
                    break
            continue
        if 'memitem' not in (el.get('class') or []):
            continue
        proto = el.find(class_='memproto')
        doc = el.find(class_='memdoc')
        sig = ''
        if proto:
            sig = _ws(proto.get_text(' ', strip=True))
            sig = re.sub(r'\s*([(),])\s*', r'\1 ', sig).replace('( ', '(').replace(' )', ')').strip()
            sig = re.sub(r'\s+', ' ', sig).replace(' ,', ',')
        name = ''
        sib = el.previous_sibling
        for _ in range(4):
            if sib is None:
                break
            if isinstance(sib, str) and 'doxytag: member=' in sib:
                m = re.search(r'member="(?:[^"]*::)?([^"]+)"', sib)
                if m:
                    name = m.group(1)
                break
            sib = sib.previous_sibling
        nm = None
        if proto:
            nm = proto.find('td', class_='memname') or proto.find(class_='memname')
        if nm and not name:
            nmt = _ws(nm.get_text(' ', strip=True))
            if kind == 'macro':
                m = re.match(r'#define\s+(\w+)', nmt)
                name = m.group(1) if m else (nmt.split()[-1] if nmt.split() else '')
            else:
                core_t = re.split(r'[=\[(]', nmt)[0]
                toks = re.findall(r'[A-Za-z_~][\w:~]*', core_t)
                name = toks[-1] if toks else nmt
        params = []
        if proto:
            for pt in proto.find_all(class_='paramname'):
                ty = pt.find_previous_sibling(class_='paramtype')
                pn = _ws(pt.get_text(' ', strip=True)).rstrip(',').strip()
                pty = _ws(ty.get_text(' ', strip=True)) if ty else ''
                if pn or (pty and pty != 'void'):
                    params.append((pn, pty, ''))
        dtext, calls, callers, ret = '', [], [], ''
        if doc:
            for dh in doc.find_all(class_='dynheader'):
                dh.decompose()
            for mp in doc.find_all('map'):
                mname = (mp.get('name') or mp.get('id') or '')
                lst = callers if 'icgraph' in mname else calls if 'cgraph' in mname else None
                if lst is not None:
                    for a in mp.find_all('area'):
                        t = a.get('title') or a.get('alt') or ''
                        if t and t not in lst and t != name:
                            lst.append(t)
                mp.decompose()
            # parameter descriptions
            for dl in doc.find_all('dl'):
                cls = ' '.join(dl.get('class') or [])
                head = dl.find('dt')
                ht = head.get_text(' ', strip=True).lower() if head else ''
                if 'param' in cls or ht.startswith('param'):
                    for tr in dl.find_all('tr'):
                        tds = tr.find_all('td')
                        if len(tds) >= 2:
                            pn = _ws(tds[-2].get_text(' ', strip=True))
                            pd = _ws(tds[-1].get_text(' ', strip=True))
                            for i, p in enumerate(params):
                                if p[0] == pn:
                                    params[i] = (p[0], p[1], pd)
                                    break
                            else:
                                params.append((pn, '', pd))
                    dl.decompose()
                elif 'return' in cls or ht.startswith('return'):
                    dd = dl.find('dd')
                    ret = _ws((dd or dl).get_text(' ', strip=True))
                    if ret.lower().startswith('returns'):
                        ret = ret[7:].strip()
                    dl.decompose()
            dtext = '\n'.join(x for x in (_ws(l) for l in doc.get_text('\n').split('\n')) if x)
            if callers:
                dtext = (dtext + '\n' if dtext else '') + 'Called by: ' + ', '.join(callers)
        if kind == 'function' and not params and '(' not in sig:
            pass
        f = {'name': name or '?', 'kind': kind, 'signature': sig, 'doc': dtext}
        if params and kind in ('function', 'constructor', 'macro', 'member'):
            f['params'] = params
        if ret:
            f['returns'] = ret
        if calls:
            f['calls'] = calls
        funcs.append(f)
        el.decompose()
    return funcs


def _javadoc_functions(soup, Tag):
    funcs, kind, kill = [], None, []
    for el in soup.find_all(['th', 'h3', 'h4']):
        if getattr(el, 'decomposed', False) or el.attrs is None:
            continue
        t = _ws(el.get_text(' ', strip=True))
        m = re.match(r'^(Field|Constructor|Method|Enum Constant|Element)\s+Detail$', t, re.I)
        if m:
            kind = {'field': 'field', 'constructor': 'constructor', 'method': 'method'}.get(m.group(1).lower(), m.group(1).lower())
            continue
        if kind is None or el.name == 'th':
            continue
        pre = el.find_next_sibling()
        if pre is None or pre.name != 'pre':
            continue
        sig = re.sub(r'\s+', ' ', pre.get_text(' ')).replace('( ', '(').replace(' )', ')').replace(' ,', ',').strip()
        parts = []
        for sib in pre.next_siblings:
            if isinstance(sib, Tag):
                if sib.name in ('h3', 'h4', 'hr') or (sib.name == 'a' and sib.get('name')):
                    break
                parts.append(sib)
        doc, params, ret, throws = [], [], '', []
        for ptag in parts:
            for dl in ptag.find_all('dl') if ptag.name != 'dl' else [ptag]:
                cur = None
                for ch in dl.find_all(['dt', 'dd'], recursive=False) if dl.find_all(['dt'], recursive=False) else []:
                    if ch.name == 'dt':
                        cur = _ws(ch.get_text(' ', strip=True)).rstrip(':').lower()
                    elif cur:
                        txt = _ws(ch.get_text(' ', strip=True))
                        if cur.startswith('param'):
                            pn, _, pd = txt.partition(' - ')
                            params.append((pn.strip(), '', pd.strip()))
                        elif cur.startswith('return'):
                            ret = txt
                        elif cur.startswith('throw'):
                            throws.append(txt)
            txt = '\n'.join(x for x in (_ws(l) for l in ptag.get_text('\n').split('\n')) if x)
            if txt:
                doc.append(txt)
            kill.append(ptag)
        full = '\n'.join(doc)
        secs = re.split(r'\n?(Parameters|Returns|Throws|See Also|Since|Specified by|Overrides|Deprecated)\s*:\s*\n?', full)
        desc = secs[0].strip()
        for k in range(1, len(secs) - 1, 2):
            key, body = secs[k], _ws(secs[k + 1].replace('\n', ' '))
            if key == 'Parameters' and not params:
                for pm in re.finditer(r'(?:^|\s)(\w+)\s+-\s+(.*?)(?=\s\w+\s+-\s+[A-Za-z]|$)', body):
                    params.append((pm.group(1), '', pm.group(2).strip()))
            elif key == 'Returns' and not ret:
                ret = body
            elif key in ('Throws', 'See Also', 'Since', 'Overrides', 'Specified by', 'Deprecated'):
                desc += f'\n{key}: {body}'
        sig = sig.replace(' (', '(')
        f = {'name': _ws(el.get_text(' ', strip=True)), 'kind': kind, 'signature': sig, 'doc': desc[:3000]}
        if params:
            f['params'] = params
        if ret:
            f['returns'] = ret
        funcs.append(f)
        kill += [el, pre]
    for k in kill:
        if not getattr(k, 'decomposed', False) and k.attrs is not None:
            k.decompose()
    return funcs


def _html(path):
    from bs4 import BeautifulSoup, Tag, NavigableString, Comment
    text, trunc = core.read_text(path, limit=12_000_000)
    head = text[:6000]
    low = head.lower()
    parser = 'html.parser'
    if len(text) > 1_000_000:
        try:
            import lxml  # noqa
            parser = 'lxml'
        except Exception:
            pass
    soup = BeautifulSoup(text, parser)
    r = {'kind': 'document', 'type': 'HTML document'}
    meta, notes, kws = [], [], []
    title = ''
    if soup.title and soup.title.string:
        title = _ws(soup.title.get_text(' '))
    gen = ''
    desc = ''
    for m in soup.find_all('meta'):
        n = (m.get('name') or m.get('http-equiv') or '').lower()
        c = _ws(m.get('content') or '')
        if n == 'generator' and c:
            gen = c
        elif n == 'description' and c:
            desc = c
        elif n == 'keywords' and c:
            kws += [k.strip() for k in re.split(r'[,;]', c) if k.strip()][:10]
    comments = [str(c) for c in soup.find_all(string=lambda s: isinstance(s, Comment))][:30]
    mdox = re.search(r'Generated by Doxygen\s*([\d.]+)?', head + text[-3000:], re.I)
    tail_low = text[-3000:].lower()
    is_dox = bool(mdox) or 'doxygen' in gen.lower() or 'doxygen.css' in low or 'www.doxygen.org' in tail_low
    mjd = re.search(r'Generated by javadoc \(?(?:build )?([^)\s]*)', head)
    is_jd = bool(mjd)
    is_jxr = (not is_jd) and title.endswith(' xref') or 'jxr' in low[:3000] and 'class="jxr' in low
    funcs = []

    if is_dox:
        r['type'] = 'Doxygen-generated HTML'
        ver = mdox.group(1) if mdox and mdox.group(1) else ''
        if not ver:
            mv = re.search(r'doxygen\.png[^>]*>\s*</a>\s*([\d.]+)', text[-3000:], re.I)
            ver = mv.group(1) if mv else ''
        mproj = re.search(r'Generated on (.+?) for (.+?) by', soup.get_text(' ')[-600:].replace('\xa0', ' '))
        for sel in ({'class': 'navigation'}, {'class': 'tabs'}, {'class': 'navpath'}, {'id': 'top'},
                    {'id': 'nav-path'}, {'id': 'side-nav'}, {'class': 'dynheader'}):
            for t in soup.find_all(attrs=sel):
                if not getattr(t, 'decomposed', False) and t.attrs is not None and not _holds_content(t):
                    t.decompose()
        for t in soup.find_all('address'):
            t.decompose()
        for t in soup.find_all(class_='footer'):
            t.decompose()
        funcs = _doxygen_functions(soup, Tag)
        for td in soup.find_all('td', class_=['memItemLeft', 'memTemplItemLeft', 'mdescLeft', 'memTemplParams']):
            td.name = 'span'
        body = soup.find(class_='contents') or soup.find(id='doc-content') or soup.body or soup
        meta.append(('Generator', 'Doxygen' + (f' {ver}' if ver else '')))
        if mproj:
            meta.append(('Doxygen project', mproj.group(2).strip()))
            meta.append(('Generated', mproj.group(1).strip()))
            kws.append(mproj.group(2).strip())
    else:
        if is_jd:
            r['type'] = 'Javadoc-generated HTML'
            meta.append(('Generator', 'javadoc' + (f' {mjd.group(1)}' if mjd.group(1) else '')))
            for td in soup.find_all(class_=re.compile(r'^NavBar')):
                tb = td.find_parent('table')
                while tb is not None and tb.find_parent('table') is not None:
                    tb = tb.find_parent('table')
                if tb is not None:
                    tb.decompose()
            for t in soup.find_all(class_=re.compile(r'^(topNav|bottomNav|subNav|navList|legalCopy)$')):
                t.decompose()
            funcs = _javadoc_functions(soup, Tag)
        elif is_jxr:
            r['type'] = 'JXR source cross-reference HTML'
        elif gen:
            r['type'] = f'HTML document (generated by {gen[:60]})'
            meta.append(('Generator', gen))
        navre = re.compile(r'^(leftcolumn|navcolumn|navbar|nav|navigation|menu|sidebar|breadcrumbs?|banner|topnav|bottomnav|subnav|skipnav)$', re.I)
        for t in soup.find_all(attrs={'id': navre}) + soup.find_all(class_=navre):
            if not getattr(t, 'decomposed', False) and t.attrs is not None and not _holds_content(t):
                t.decompose()
        body = soup.body or soup
    if title:
        r['title'] = title
    if desc:
        meta.append(('Description', desc))
    if trunc:
        notes.append('File larger than 12 MB: only the first 12 MB parsed.')
    if soup.find('frameset') is not None:
        frames = [f.get('src') for f in soup.find_all('frame') if f.get('src')]
        if frames:
            r['outline'] = [{'heading': 'Frames'}] + frames
            r['type'] = 'HTML frameset'

    pars = _html_blocks(body, Tag, NavigableString, Comment)
    pars = _clean_heads(pars)
    if not (is_dox or is_jd or is_jxr):
        ls = [l for p in pars if isinstance(p, str) for l in p.split('\n')][:400]
        if len(ls) > 8 and sum(bool(re.match(r'^\s*\d{1,5}\s', l)) for l in ls) > 0.7 * len(ls):
            is_jxr = True
            r['type'] = 'HTML source-code listing (line-numbered)'
    if is_dox and title:
        # first <h1> usually repeats the title
        if pars and isinstance(pars[0], dict) and pars[0]['heading'] in title:
            pars = pars[1:]
    if len(pars) > MAX_PARS:
        notes.append(f'{len(pars):,} blocks; first {MAX_PARS:,} kept.')
        pars = pars[:MAX_PARS]
    r['paragraphs'] = pars
    if funcs:
        r['functions'] = funcs
        r['code_lang'] = 'java' if is_jd else 'c'
    plain = '\n'.join(p for p in pars if isinstance(p, str))

    # ---- specialised summaries
    summ = ''
    if is_dox:
        cnt = collections.Counter(f['kind'] for f in funcs)
        what = ', '.join(f'{n} {k}{"s" if n != 1 else ""}' for k, n in cnt.most_common())
        proj = dict(meta).get('Doxygen project', '')
        summ = f'Doxygen-generated documentation page "{title or os.path.basename(path)}"' + (f' (project {proj})' if proj else '')
        if funcs:
            summ += f', documenting {what}: ' + ', '.join(f['name'] for f in funcs[:15]) + (' …' if len(funcs) > 15 else '')
        summ += '.'
        brief = next((p for p in pars if isinstance(p, str) and len(p) > 40 and '\n' not in p and not p.startswith('#')
                      and len(p.split()) >= 6 and not p.startswith('The documentation for this')), '')
        src = [l for p in pars if isinstance(p, str) for l in p.split('\n') if re.match(r'^\d{5}\s', l)]
        if len(src) > 3:
            com = []
            for l in src[:40]:
                c = l[5:].strip()
                if c.startswith(('//', '/*', '*', ';')) or (com and c.startswith('*')):
                    c = c.strip('/*; ').strip()
                    if c and not re.match(r'^[-=*_]+$', c):
                        com.append(c)
                elif c:
                    break
            summ += f' Source-code listing of {len(src):,} lines.'
            if com:
                summ += ' Header comment: ' + ' '.join(com)[:300]
        elif brief and len(summ) < 300:
            summ += ' ' + brief[:300]
    elif is_jd:
        lead = next((p for p in pars if isinstance(p, str) and len(p) > 60 and not p.startswith(('Copyright', 'public ', 'protected ', 'Overview', 'All Classes'))
                     and '|' not in p[:40]), '')
        summ = f'Javadoc-generated API documentation page "{title or os.path.basename(path)}"'
        if funcs:
            cnt = collections.Counter(f['kind'] for f in funcs)
            summ += ', documenting ' + ', '.join(f'{n} {k}{"s" if n != 1 else ""}' for k, n in cnt.most_common())
            summ += ': ' + ', '.join(dict.fromkeys(f['name'] for f in funcs[:15])) + (' …' if len(funcs) > 15 else '')
        summ += '.'
        if lead:
            summ += ' ' + core.summarize([lead], max_sent=2, max_chars=300)
    elif is_jxr:
        src = '\n'.join(p for p in pars if isinstance(p, str))
        pk = re.search(r'^\s*\d*\s*package\s+([\w.]+)', src, re.M)
